//! Device-side feedback pixels, not OS input or evidence of task completion.
//! Native presentation is isolated from the portable raster and lifetime policy.
#[cfg(windows)]
mod native;
#[cfg(windows)]
pub(crate) use native::{Gesture, start, status, stop, suspend_capture};

pub(super) const SIZE: usize = 72;
pub(super) const MAX_SCALE: u32 = 3;
pub(super) const HIGHLIGHT_MS: u64 = 800;

/// A hide acknowledgement must follow the suspension request, not an older
/// renderer snapshot. Nested capture guards cannot resume each other's display.
#[derive(Default)]
pub(super) struct CaptureGate {
    pub revision: u64,
    pub applied_revision: u64,
    pub suspended: usize,
    pub visible: bool,
}
impl CaptureGate {
    pub fn changed(&mut self) {
        self.revision += 1;
    }
    pub fn suspend(&mut self) -> u64 {
        self.suspended += 1;
        self.changed();
        self.revision
    }
    pub fn resume(&mut self) {
        self.suspended = self.suspended.saturating_sub(1);
        self.changed();
    }
    pub fn acknowledge(&mut self, revision: u64, visible: bool) {
        self.applied_revision = revision;
        self.visible = visible;
    }
    pub fn capture_ready(&self, ticket: u64) -> bool {
        self.suspended > 0 && self.applied_revision >= ticket && !self.visible
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize)]
#[serde(rename_all = "snake_case")]
pub(super) enum Phase {
    Idle,
    Pointer,
    Pressed,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize)]
pub(super) struct Anchor {
    pub point: [i32; 2],
    pub scale: u32,
}

pub(super) fn marker(
    anchor: Option<Anchor>,
    active: Option<(Anchor, Phase)>,
    suspended: bool,
) -> Option<(Anchor, Phase)> {
    if suspended {
        None
    } else {
        active.or_else(|| anchor.map(|a| (a, Phase::Idle)))
    }
}

pub(super) fn scale_for_dpi(dpi: u32) -> u32 {
    dpi.div_ceil(96).clamp(1, MAX_SCALE)
}

/// Premultiplied BGRA for UpdateLayeredWindow, generated by the native product.
/// A fixed RCU badge distinguishes our feedback from other agents' pointers.
pub(super) fn raster(scale: u32, phase: Phase) -> Vec<u8> {
    let scale = scale.clamp(1, MAX_SCALE) as usize;
    let size = SIZE * scale;
    let mut pixels = vec![0; size * size * 4];
    for y in 0..size {
        for x in 0..size {
            let px = (x as f64 + 0.5) / scale as f64;
            let py = (y as f64 + 0.5) / scale as f64;
            let radius = (px - 36.).hypot(py - 36.);
            let strength = if phase == Phase::Idle { 95. } else { 145. };
            let mut alpha = ((1. - radius / 28.).max(0.).powi(2) * strength) as u8;
            if phase == Phase::Pressed && (radius - 12.).abs() < 1.25 {
                alpha = 220;
            }
            let i = (y * size + x) * 4;
            let [blue, green, red] = if phase == Phase::Idle {
                [170, 170, 170]
            } else {
                [244, 160, 40]
            };
            pixels[i..i + 4].copy_from_slice(&[
                (u16::from(alpha) * blue / 255) as u8,
                (u16::from(alpha) * green / 255) as u8,
                (u16::from(alpha) * red / 255) as u8,
                alpha,
            ]);
            let ax = px - 36.;
            let ay = py - 36.;
            let inside = arrow(ax, ay);
            let border = !inside
                && [(-1., 0.), (1., 0.), (0., -1.), (0., 1.)]
                    .iter()
                    .any(|(dx, dy)| arrow(ax + dx, ay + dy));
            if inside || border {
                let value = if inside { 24 } else { 250 };
                pixels[i..i + 4].copy_from_slice(&[value, value, value, 255]);
            }
            if (44. ..65.).contains(&px) && (61. ..72.).contains(&py) {
                pixels[i..i + 4].copy_from_slice(&[24, 24, 24, 225]);
            }
            if badge(px, py) {
                pixels[i..i + 4].copy_from_slice(&[255; 4]);
            }
        }
    }
    pixels
}

fn arrow(x: f64, y: f64) -> bool {
    const POLYGON: [[f64; 2]; 7] = [
        [0., 0.],
        [0., 21.],
        [5., 16.],
        [10., 25.],
        [14., 23.],
        [9., 14.],
        [18., 14.],
    ];
    let mut inside = false;
    let mut previous = POLYGON.len() - 1;
    for (i, point) in POLYGON.iter().enumerate() {
        let prior = POLYGON[previous];
        if (point[1] > y) != (prior[1] > y)
            && x < (prior[0] - point[0]) * (y - point[1]) / (prior[1] - point[1]) + point[0]
        {
            inside = !inside;
        }
        previous = i;
    }
    inside
}

fn badge(x: f64, y: f64) -> bool {
    // Three five-pixel letters. No user text, document data, or executable names.
    const LETTERS: [[u8; 7]; 3] = [
        [30, 17, 17, 30, 20, 18, 17],
        [14, 17, 16, 16, 16, 17, 14],
        [17, 17, 17, 17, 17, 17, 14],
    ];
    if !(46. ..63.).contains(&x) || !(63. ..70.).contains(&y) {
        return false;
    }
    let x = (x - 46.) as usize;
    let y = (y - 63.) as usize;
    x % 6 < 5 && (LETTERS[x / 6][y] & (1 << (4 - x % 6))) != 0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dpi_and_allocation_are_bounded() {
        assert_eq!([0, 96, 144, 192, 768].map(scale_for_dpi), [1, 1, 2, 2, 3]);
        assert_eq!(raster(u32::MAX, Phase::Pointer).len(), SIZE * SIZE * 9 * 4);
        const { assert!(HIGHLIGHT_MS <= 1000) };
    }

    #[test]
    fn pixels_are_premultiplied_with_transparent_edges() {
        for phase in [Phase::Idle, Phase::Pointer, Phase::Pressed] {
            let pixels = raster(2, phase);
            assert!(
                pixels
                    .chunks_exact(4)
                    .all(|p| p[..3].iter().all(|v| *v <= p[3]))
            );
            assert_eq!(&pixels[..4], &[0; 4]);
            assert!(pixels.chunks_exact(4).any(|p| p[3] > 0 && p[3] < 255));
            assert!(pixels.chunks_exact(4).any(|p| p == [24, 24, 24, 255]));
        }
    }

    #[test]
    fn press_feedback_and_badge_are_distinct_and_deterministic() {
        assert_ne!(raster(1, Phase::Idle), raster(1, Phase::Pointer));
        assert_ne!(raster(1, Phase::Pointer), raster(1, Phase::Pressed));
        assert_eq!(raster(1, Phase::Pointer), raster(1, Phase::Pointer));
        assert!(badge(46., 63.));
        assert!(!badge(63., 63.));
        assert!(!badge(0., 0.));
    }

    #[test]
    fn idle_marker_exists_without_an_action_and_survives_action_end() {
        let seed = Anchor {
            point: [-20, 100],
            scale: 2,
        };
        assert_eq!(marker(Some(seed), None, false), Some((seed, Phase::Idle)));
        let last = Anchor {
            point: [200, 300],
            scale: 1,
        };
        assert_eq!(
            marker(Some(last), Some((last, Phase::Pressed)), false),
            Some((last, Phase::Pressed))
        );
        assert_eq!(marker(Some(last), None, false), Some((last, Phase::Idle)));
        assert_eq!(marker(Some(last), None, true), None);
        assert_eq!(marker(Some(last), None, false), Some((last, Phase::Idle)));
        assert_eq!(marker(None, None, false), None);
    }

    #[test]
    fn in_flight_old_render_cannot_acknowledge_a_capture() {
        let mut gate = CaptureGate::default();
        gate.changed();
        let rendering = gate.revision;
        let ticket = gate.suspend();
        gate.acknowledge(rendering, true);
        assert!(!gate.capture_ready(ticket));
        gate.acknowledge(rendering, false);
        assert!(!gate.capture_ready(ticket));
        gate.acknowledge(ticket, false);
        assert!(gate.capture_ready(ticket));
    }

    #[test]
    fn nested_capture_and_new_input_stay_hidden_until_all_guards_leave() {
        let mut gate = CaptureGate::default();
        let first = gate.suspend();
        let second = gate.suspend();
        gate.changed(); // input feedback arrives during capture
        gate.acknowledge(gate.revision, false);
        assert!(gate.capture_ready(first) && gate.capture_ready(second));
        gate.resume();
        assert_eq!(gate.suspended, 1);
        gate.resume();
        assert_eq!(gate.suspended, 0);
        assert!(!gate.capture_ready(second));
    }
}
